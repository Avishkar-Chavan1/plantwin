/** Pure presentation helpers (no React) so they can be unit-tested with the Node test runner. */

export type SourceMode = "LIVE_READ_ONLY" | "SIMULATION" | "HISTORICAL" | "MIXED_DATA_BLOCKED" | "NO_DATA";
type Tone = "live" | "sim" | "hist" | "warn" | "bad" | "idle";

const MODE_LABELS: Record<SourceMode, { label: string; tone: Tone; description: string }> = {
  LIVE_READ_ONLY: { label: "LIVE · READ-ONLY", tone: "live", description: "Values are read from a configured connector. Nothing is written to the plant." },
  SIMULATION: { label: "SIMULATION", tone: "sim", description: "Values are generated by a simulator, not measured on a plant." },
  HISTORICAL: { label: "HISTORICAL", tone: "hist", description: "Values are archival records, not the current plant state." },
  MIXED_DATA_BLOCKED: { label: "MIXED SOURCES · BLOCKED", tone: "bad", description: "Live, historical and simulated values are never combined." },
  NO_DATA: { label: "NO DATA", tone: "idle", description: "No telemetry has been received for this organization yet." },
};

export function normalizeMode(value: unknown): SourceMode {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(MODE_LABELS, value) ? (value as SourceMode) : "NO_DATA";
}

export function modeInfo(mode: SourceMode) {
  return MODE_LABELS[mode];
}

export function formatAge(seconds: number | null | undefined): string {
  if (seconds === null || seconds === undefined || !Number.isFinite(seconds)) return "—";
  if (seconds < 90) return `${Math.round(seconds)} s ago`;
  if (seconds < 5400) return `${Math.round(seconds / 60)} min ago`;
  if (seconds < 172_800) return `${(seconds / 3600).toFixed(1)} h ago`;
  return `${Math.round(seconds / 86_400)} d ago`;
}

export function formatNumber(value: number | null | undefined, digits = 2): string {
  return value === null || value === undefined || !Number.isFinite(value) ? "—" : value.toFixed(digits);
}

export function formatTimestamp(value: string | null | undefined): string {
  if (!value) return "—";
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? "—" : date.toLocaleString();
}
