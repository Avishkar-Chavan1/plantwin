"""Dashboard summary: every value is read from the database or computed from stored state.

Nothing here fabricates a measurement. When a value is unavailable the field is ``None`` (or the
section is empty) and the UI says so. Data provenance is explicit on every measurement
(``source`` / ``source_mode``), and live values are checked for staleness at *read* time, not
only at ingest time, so a dead connector cannot leave an old "healthy" state on screen.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any
from uuid import UUID

from packages.units import convert
from sqlalchemy import desc, func, select
from sqlalchemy.orm import Session

from .auth import TenantContext
from .models import (
    Alert,
    DataSource,
    Equipment,
    ModelVersion,
    Plant,
    QualityStatusName,
    Recommendation,
    Sensor,
    SensorReading,
    TwinState,
)
from .realtime import source_mode
from .time_utils import as_utc

SAFETY_NOTICES = {
    "LIVE_READ_ONLY": "LIVE READ-ONLY: values are read from a configured source. "
    "ProcessTwin sends no commands to the plant.",
    "HISTORICAL": "HISTORICAL data: archival values, not current plant state. No control connection exists.",
    "SIMULATION": "SIMULATION: values are generated by a synthetic simulator, not measured on a plant.",
    "MIXED_DATA_BLOCKED": "SIMULATION, HISTORICAL and LIVE READ-ONLY values are never combined. "
    "Resolve the mixed sources before relying on this view.",
    "NO_DATA": "No telemetry is available yet. Configure a read-only connector, import data, or "
    "start the simulator.",
}

MIN_STALE_AFTER_S = 30.0


def _stale_threshold_s(sensor: Sensor) -> float:
    return max(MIN_STALE_AFTER_S, 3.0 * float(sensor.sampling_interval_s or 0))


def _tenant_sections(session: Session, organization_id: UUID, now: datetime) -> dict[str, Any]:
    """Sections that are organisation-wide rather than equipment-specific."""
    sources = list(
        session.scalars(
            select(DataSource)
            .where(DataSource.organization_id == organization_id)
            .order_by(desc(DataSource.updated_at))
            .limit(50)
        )
    )
    from .live_api import source_payload

    connector_items = []
    for source in sources:
        payload = source_payload(source, now)
        connector_items.append(
            {
                "id": payload["id"],
                "name": payload["name"],
                "source_type": payload["source_type"],
                "status": payload["status"],
                "read_only": payload["read_only"],
                "last_success_at": payload["last_success_at"],
                "freshness_s": payload["freshness_s"],
                "tags": payload["mappings"],
            }
        )
    open_alerts = list(
        session.scalars(
            select(Alert)
            .where(Alert.organization_id == organization_id, Alert.status == "OPEN")
            .order_by(desc(Alert.occurred_at))
            .limit(5)
        )
    )
    open_alert_count = (
        session.scalar(
            select(func.count())
            .select_from(Alert)
            .where(Alert.organization_id == organization_id, Alert.status == "OPEN")
        )
        or 0
    )
    model = session.scalar(
        select(ModelVersion)
        .where(
            ModelVersion.organization_id == organization_id,
            ModelVersion.status.in_(("PRODUCTION", "STAGING", "VALIDATED")),
        )
        .order_by(desc(ModelVersion.status == "PRODUCTION"), desc(ModelVersion.created_at))
        .limit(1)
    )
    model_count = (
        session.scalar(
            select(func.count())
            .select_from(ModelVersion)
            .where(ModelVersion.organization_id == organization_id)
        )
        or 0
    )
    pending = (
        session.scalar(
            select(func.count())
            .select_from(Recommendation)
            .where(
                Recommendation.organization_id == organization_id,
                Recommendation.status.in_(("GENERATED", "REVIEWED")),
            )
        )
        or 0
    )
    latest_recommendations = list(
        session.scalars(
            select(Recommendation)
            .where(
                Recommendation.organization_id == organization_id,
                Recommendation.status.in_(("GENERATED", "REVIEWED")),
            )
            .order_by(desc(Recommendation.created_at))
            .limit(3)
        )
    )
    return {
        "connectors": {"count": len(connector_items), "items": connector_items},
        "alerts": {
            "open_count": int(open_alert_count),
            "items": [
                {
                    "id": str(alert.id),
                    "severity": alert.severity.value,
                    "reason": alert.reason,
                    "timestamp": alert.occurred_at,
                }
                for alert in open_alerts
            ],
        },
        "models": {
            "count": int(model_count),
            "active": None
            if model is None
            else {
                "id": str(model.id),
                "name": model.name,
                "version": model.version,
                "type": model.model_type,
                "status": model.status,
                "has_operating_envelope": bool(model.operating_envelope),
            },
            "validation_note": "No VALIDATED, STAGING or PRODUCTION model is registered; "
            "predictions are unvalidated reference calculations."
            if model is None
            else "Model status reflects internal evaluation records only. This is not evidence of "
            "validation against a real plant.",
        },
        "recommendations": {
            "pending_review_count": int(pending),
            "items": [
                {
                    "id": str(item.id),
                    "text": item.text,
                    "status": item.status,
                    "timestamp": item.created_at,
                    "expires_at": item.expires_at,
                }
                for item in latest_recommendations
            ],
        },
    }


def _empty_equipment_view(message: str) -> dict[str, Any]:
    return {
        "equipment": None,
        "source_mode": "NO_DATA",
        "plant_health": "NO_DATA",
        "data_state": "NO_DATA",
        "measurements": {},
        "twin": None,
        "data_quality": {"sensor_count": 0, "sensors_with_data": 0},
        "safety_notice": SAFETY_NOTICES["NO_DATA"],
        "message": message,
    }


def dashboard_payload(
    context: TenantContext,
    session: Session,
    equipment_id: UUID | None = None,
    now: datetime | None = None,
) -> dict[str, Any]:
    current = as_utc(now or datetime.now(UTC))
    org = context.organization_id
    equipment_rows = list(
        session.scalars(
            select(Equipment)
            .where(Equipment.organization_id == org)
            .order_by(Equipment.created_at)
            .limit(100)
        )
    )
    tenant = _tenant_sections(session, org, current)
    base: dict[str, Any] = {"generated_at": current, **tenant}
    if not equipment_rows:
        return {**base, **_empty_equipment_view("No equipment configured")}
    selected = next((item for item in equipment_rows if item.id == equipment_id), equipment_rows[0])
    plant = session.get(Plant, selected.plant_id)
    equipment_summary = {"id": str(selected.id), "tag": selected.tag, "name": selected.name}
    base["plant"] = {"id": str(plant.id), "name": plant.name} if plant is not None else None
    base["equipment_options"] = [
        {"id": str(item.id), "tag": item.tag, "name": item.name} for item in equipment_rows
    ]

    sensors = list(
        session.scalars(
            select(Sensor)
            .where(Sensor.equipment_id == selected.id, Sensor.organization_id == org)
            .order_by(Sensor.tag)
        )
    )
    latest: dict[str, dict[str, Any]] = {}
    modes: set[str] = set()
    stale_tags: list[str] = []
    suspect_tags: list[str] = []
    for sensor in sensors:
        reading = session.scalar(
            select(SensorReading)
            .where(
                SensorReading.sensor_id == sensor.id,
                SensorReading.organization_id == org,
                SensorReading.quality_status.in_(
                    (QualityStatusName.GOOD, QualityStatusName.SUSPECT)
                ),
            )
            .order_by(desc(SensorReading.timestamp))
            .limit(1)
        )
        if reading is None:
            continue
        mode = source_mode(reading.source)
        modes.add(mode)
        age_s = max(0.0, (current - as_utc(reading.timestamp)).total_seconds())
        # Archival data has no meaningful "age"; live and simulated values do.
        stale = None if mode == "HISTORICAL" else age_s > _stale_threshold_s(sensor)
        if stale:
            stale_tags.append(sensor.tag)
        if reading.quality_status is QualityStatusName.SUSPECT:
            suspect_tags.append(sensor.tag)
        latest[sensor.tag] = {
            "name": sensor.name,
            "measurement_type": sensor.measurement_type,
            "value": reading.value,
            "unit": reading.unit,
            "quality_status": reading.quality_status.value,
            "quality_reasons": reading.quality_reasons,
            "source": reading.source,
            "source_mode": mode,
            "timestamp": reading.timestamp,
            "age_s": age_s,
            "stale": stale,
            "stale_after_s": _stale_threshold_s(sensor),
        }
    missing_tags = [sensor.tag for sensor in sensors if sensor.tag not in latest]
    data_quality = {
        "sensor_count": len(sensors),
        "sensors_with_data": len(latest),
        "missing_tags": missing_tags,
        "stale_tags": stale_tags,
        "suspect_tags": suspect_tags,
    }
    result: dict[str, Any] = {
        **base,
        "equipment": equipment_summary,
        "data_quality": data_quality,
    }

    if len(modes) > 1:
        return {
            **result,
            "source_mode": "MIXED_DATA_BLOCKED",
            "plant_health": "MIXED_DATA_BLOCKED",
            "data_state": "BLOCKED",
            "measurements": {},
            "twin": None,
            "safety_notice": SAFETY_NOTICES["MIXED_DATA_BLOCKED"],
        }
    if not modes:
        return {
            **result,
            "source_mode": "NO_DATA",
            "plant_health": "NO_DATA",
            "data_state": "NO_DATA",
            "measurements": {},
            "twin": None,
            "safety_notice": SAFETY_NOTICES["NO_DATA"],
        }

    mode = next(iter(modes))
    stored = session.scalar(
        select(TwinState)
        .where(
            TwinState.organization_id == org,
            TwinState.equipment_id == selected.id,
            TwinState.source_mode == mode,
        )
        .order_by(desc(TwinState.timestamp))
        .limit(1)
    )
    all_stale = bool(latest) and len(stale_tags) == len(latest)
    any_stale = bool(stale_tags)
    twin_body: dict[str, Any] | None = None
    if stored is None:
        health = "WAITING_FOR_SYNCHRONIZED_TWIN"
    else:
        physics_state = stored.state.get("physics", {}) or {}
        measured = stored.state.get("measurements", {})
        measured_temperature = measured.get("reactor.temperature", {})
        selected_temperature = measured_temperature.get("normalized_value")
        if selected_temperature is None:
            selected_temperature = physics_state.get("temperature_k")

        def estimate(key: str, scale: float, unit: str) -> dict[str, Any] | None:
            value = physics_state.get(key)
            if value is None:
                return None
            return {
                "value": float(value) * scale,
                "unit": unit,
                "source": "ESTIMATED",
                "timestamp": stored.timestamp,
            }

        twin_body = {
            "timestamp": stored.timestamp,
            "temperature": None
            if selected_temperature is None
            else {
                "value": convert(float(selected_temperature), "K", "degC"),
                "unit": "degC",
                "source": "MEASURED" if measured_temperature else "ESTIMATED",
                "timestamp": stored.timestamp,
            },
            "conversion": estimate("conversion", 100.0, "%"),
            "yield": estimate("yield", 100.0, "%"),
            "selectivity": estimate("selectivity", 100.0, "%"),
            "heat_removal": estimate("heat_removal_w", 0.001, "kW"),
            "divergence_temperature_k": stored.state.get("physics_residual_temperature_k"),
            "prediction_status": stored.prediction_status,
            "uncertainty": stored.uncertainty,
            "data_quality": stored.data_quality,
            "health_factors": stored.health_factors,
            "model_version_id": str(stored.model_version_id) if stored.model_version_id else None,
            "physics_parameter_set_id": str(stored.physics_parameter_set_id)
            if stored.physics_parameter_set_id
            else None,
            "stale": any_stale,
        }
        health = stored.health_status
        if any_stale and mode != "HISTORICAL":
            # Model outputs derived from stale inputs are withheld, never shown as current.
            health = "STALE_DATA"
            for key in ("conversion", "yield", "selectivity", "heat_removal"):
                twin_body[key] = None
            twin_body["withheld_reason"] = (
                "Estimated values are withheld because input data is stale: "
                + ", ".join(sorted(stale_tags))
            )
        elif stored.prediction_status in {
            "WAITING_FOR_REQUIRED_INPUTS",
            "BLOCKED_MIXED_SOURCES",
            "PREDICTION_ERROR",
        }:
            twin_body["withheld_reason"] = {
                "WAITING_FOR_REQUIRED_INPUTS": "Required model inputs are not mapped or have no data.",
                "BLOCKED_MIXED_SOURCES": "Inputs come from mixed data sources.",
                "PREDICTION_ERROR": "The model could not produce a prediction.",
            }[stored.prediction_status]
        elif stored.prediction_status == "OUTSIDE_VALIDATED_MODEL_RANGE":
            twin_body["withheld_reason"] = "Operating point is outside the validated model range."

    data_state = "OK"
    if mode != "HISTORICAL" and all_stale:
        data_state = "STALE"
    elif any_stale:
        data_state = "PARTIALLY_STALE"
    elif missing_tags:
        data_state = "INCOMPLETE"
    return {
        **result,
        "source_mode": mode,
        "plant_health": health,
        "data_state": data_state,
        "measurements": latest,
        "twin": twin_body,
        "active_alerts": tenant["alerts"]["open_count"],
        "safety_notice": SAFETY_NOTICES.get(mode, SAFETY_NOTICES["NO_DATA"]),
    }
